export const STRINGS: Record<string, Strings> = { en, ko, zh };

function lang(): string {
  const l = (getLanguage?.() || 'en').toLowerCase();
  if (l.startsWith('ko')) return 'ko';
  if (l.startsWith('zh')) return 'zh';
  return 'en';
}

export function locale(): string {
  return { ko: 'ko-KR', zh: 'zh-CN', en: 'en-US' }[lang()] ?? 'en-US';
}

export function t(key: StringKey, vars: Record<string, string | number> = {}): string {
  const s = (STRINGS[lang()] ?? en)[key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_m, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function plural(base: 'head.count' | 'query.count', n: number): string {
  return n === 1 ? t(`${base}.one` as StringKey) : t(`${base}.many` as StringKey, { n });
}
